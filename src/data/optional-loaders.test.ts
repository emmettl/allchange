import { beforeEach, afterEach, expect, it, vi } from 'vitest'
import { fixtureResponse, installFixtureFetch } from '../test/fixture-fetch.ts'

beforeEach(() => { vi.resetModules() })
afterEach(() => { vi.unstubAllGlobals() })
it('deduplicates cycle manifests, days and comparison profiles, evicts rejected downloads and avoids other journey days', async () => {
  const { overrides, requests } = installFixtureFetch()
  const { loadCycleDay } = await import('./cycle-hire.ts')
  const { loadCycleComparison } = await import('./cycle-comparison.ts')
  overrides.set('2026-05-29.json', () => new Response('', { status: 503 }))
  await expect(loadCycleDay()).rejects.toThrow()
  overrides.clear()
  const [a, b] = await Promise.all([loadCycleDay(), loadCycleDay()])
  expect(a.day).toBe(b.day)
  expect(requests('manifest.json')).toHaveLength(1)
  expect(requests('2026-05-29.json')).toHaveLength(2)
  overrides.set('/profiles/1072.json', () => Response.json({ dockId: 'wrong' }))
  await expect(loadCycleComparison('1072', a.manifest)).rejects.toThrow()
  overrides.clear()
  const [first, second] = await Promise.all([loadCycleComparison('1072', a.manifest), loadCycleComparison('1072', a.manifest)])
  expect(first).toBe(second)
  expect(requests('/profiles/1072.json')).toHaveLength(2)
  expect(requests('/days/')).toHaveLength(2)
})

it('loads only the selected passenger area, retries bad data and separates Thursday carry-in from Friday', async () => {
  const { overrides, requests } = installFixtureFetch()
  const { loadPassengerSelection } = await import('./passenger-demand.ts')
  overrides.set('/stations/BNKu.json', () => new Response('', { status: 503 }))
  await expect(loadPassengerSelection('Bank')).rejects.toThrow()
  overrides.clear()
  const [bank, monument] = await Promise.all([loadPassengerSelection('Bank'), loadPassengerSelection('Monument')])
  expect(bank!.data).toBe(monument!.data)
  expect(requests('/stations/BNKu.json')).toHaveLength(2)
  expect((await loadPassengerSelection('Bank', undefined, true))!.data.start).toBe(0)
  expect(bank!.data.start).toBe(18000)
  const wharf = await loadPassengerSelection('Canary Wharf', 'CAWd')
  expect(wharf!.data.station.asc).toBe('CAWd')
  expect(wharf!.areas).toHaveLength(3)
  expect(await loadPassengerSelection('Addington Village')).toBeUndefined()
  expect(requests('/stations/ADVt.json')).toHaveLength(0)
  expect(requests('catalogue.json')).toHaveLength(1)
})

it('retries an optional directional study after failure and shares the successful download', async () => {
  const { overrides, requests } = installFixtureFetch()
  const { loadMorningFlow } = await import('./morning-flow.ts')
  overrides.set('all-change-morning-flow.json', () => new Response('', { status: 503 }))
  await expect(loadMorningFlow()).rejects.toThrow()
  overrides.set('all-change-morning-flow.json', () => fixtureResponse('/data/all-change-morning-flow.json'))
  const [first, second] = await Promise.all([loadMorningFlow(), loadMorningFlow()])
  expect(first).toBe(second)
  expect(requests('all-change-morning-flow.json')).toHaveLength(2)
})
